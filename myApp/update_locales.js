const fs = require('fs');

function updateJson(filepath, translations) {
    const data = JSON.parse(fs.readFileSync(filepath, 'utf8'));
    if (!data.screens) data.screens = {};
    if (!data.screens.newSheet) data.screens.newSheet = {};
    
    Object.assign(data.screens.newSheet, translations);
    
    fs.writeFileSync(filepath, JSON.stringify(data, null, 2), 'utf8');
}

